#!/bin/sh
# 判据：契约收口对照表成立——**后续每一步开工前能逐条比对的一页表**。
#
# 为什么要它：契约是一篇文章，文章没法在开工前"逐条打勾"。这一格要把裁定压成
# 一张**行=裁定、列=(裁定内容/违反时的现象/在哪一步生效)** 的表；没有这张表，
# 六步实现走到第 3 步时没人会回头翻契约。
#
# 四态：0=通过；1=不通过；2=不可判。
set -u
T=.team/nodes/t.close/裁定对照表.md
C=docs/输入透传契约.md

[ -f "$C" ] || { echo "UNJUDGEABLE 上游契约 ${C} 不在，收口无从核起"; exit 2; }
[ -f "$T" ] || { echo "FAIL 对照表不存在：${T}"; exit 1; }

# 必须是表格：至少 8 行以 | 开头的表行（表头+分隔+>=6 条裁定）
ROWS=$(grep -c '^ *|' "$T" 2>/dev/null || echo 0)
[ "$ROWS" -ge 8 ] || { echo "FAIL ${T} 只有 ${ROWS} 行表行（要求 >=8：表头+分隔+至少 6 条裁定）"; exit 1; }

# 每条裁定必须带"违反时看到什么现象"——⛔ 只写结论的表没法用来排障
[ "$(grep -c '现象\|症状' "$T")" -ge 1 ] || {
  echo "FAIL 对照表没有「违反时的现象」这一列——只写结论的表在排障时用不上"; exit 1; }

# 关键裁定必须都在表里出现
miss=""
for k in 1006 1002 1003 tmux ack send-keys GPLv3; do
  grep -q "$k" "$T" || miss="$miss $k"
done
[ -z "$miss" ] || { echo "FAIL 对照表漏了这些裁定：${miss}"; exit 1; }

echo "PASS ${T}：${ROWS} 行表行、含现象列、7 项关键裁定齐"
exit 0
